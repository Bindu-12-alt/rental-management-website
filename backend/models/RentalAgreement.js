const mongoose = require('mongoose');

const RentalAgreementSchema = new mongoose.Schema({
  agreementId: { type: String, required: true, unique: true, trim: true },
  tenant: { type: mongoose.Schema.Types.ObjectId, ref: 'Tenant', required: true },
  apartment: { type: mongoose.Schema.Types.ObjectId, ref: 'Apartment', required: true },
  startDate: { type: Date, required: true },
  expiryDate: { type: Date, required: true },
  rentalCycle: { type: String, required: true, trim: true },
  monthlyRent: { type: Number, required: true, min: 0 },
  status: {
    type: String,
    enum: ['Draft', 'Generated', 'Pending Signature', 'Signed', 'Active', 'Expiring Soon', 'Expired', 'Ending', 'Renewed', 'Terminated'],
    default: 'Generated',
  },
  agreementDetails: { type: String },
  maintenanceCharges: { type: Number, min: 0, default: 0 },
  securityDeposit: { type: Number, min: 0, default: 0 },
  renewalTerms: { type: String, default: '' },
  legalConditions: { type: String, default: '' },
  tenantSnapshot: { type: mongoose.Schema.Types.Mixed },
  apartmentSnapshot: { type: mongoose.Schema.Types.Mixed },
  documentData: { type: Buffer },
  documentOriginalName: { type: String },
  documentSource: { type: String, enum: ['generated', 'uploaded'] },
  emailDeliveryStatus: {
    type: String,
    enum: ['not_sent', 'sending', 'sent', 'failed', 'not_configured'],
    default: 'not_sent',
  },
  emailSentAt: { type: Date },
  emailSendingAt: { type: Date },
  emailMessageId: { type: String },
  emailError: { type: String },
  emailAttempts: { type: Number, default: 0 },
  signatureProvider: { type: String, enum: ['docusign'] },
  signatureEnvelopeId: { type: String, select: false },
  signatureTransactionId: { type: String, select: false },
  signatureStatus: {
    type: String,
    enum: ['not_started', 'sending', 'sent', 'delivered', 'completed', 'sandbox_completed', 'declined', 'voided', 'failed', 'unknown'],
    default: 'not_started',
  },
  signatureSentAt: { type: Date },
  signatureCompletedAt: { type: Date },
  signatureLastCheckedAt: { type: Date },
  signatureDocumentAvailable: { type: Boolean, default: false },
  signatureSendingAt: { type: Date, select: false },
  signatureAttempts: { type: Number, default: 0 },
  signatureError: { type: String, select: false },
  signedDocumentData: { type: Buffer, select: false },
  renewalReminderSentAt: { type: Date },
  renewalReminderError: { type: String },
  renewalReminderWhatsAppSentAt: { type: Date },
  expiryNotificationSentAt: { type: Date },
  expiryNotificationError: { type: String },
  renewals: [{ type: mongoose.Schema.Types.ObjectId, ref: 'RentalAgreement' }],
}, { timestamps: true });

module.exports = mongoose.model('RentalAgreement', RentalAgreementSchema);
